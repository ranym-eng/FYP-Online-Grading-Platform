export function translateText(value, language = activeLanguage) {
  if (value === null || value === undefined) return value
  const text = String(value)
  const match = text.match(/^(\s*)([\s\S]*?)(\s*)$/)
  const core = match?.[2] || text
  if (!core) return text
  const exact = exactByLanguage[language]?.get(core.toLocaleLowerCase(language))
  const translated = exact || translateDynamic(core, language)
  return `${match?.[1] || ''}${translated}${match?.[3] || ''}`
}

export function getInitialLanguage() {
  const saved = localStorage.getItem(LANGUAGE_KEY)
  const language = saved === 'fr' || saved === 'en' ? saved : (navigator.language?.toLowerCase().startsWith('fr') ? 'fr' : 'en')
  activeLanguage = language
  return language
}

export function setLanguagePreference(language) {
  activeLanguage = language
  localStorage.setItem(LANGUAGE_KEY, language)
  document.documentElement.lang = language
  document.title = language === 'fr' ? 'Plateforme de notation FYP | SQU' : 'FYP Grading Platform | SQU'
}

export function currentLocale() {
  return activeLanguage === 'fr' ? 'fr-FR' : 'en-GB'
}

export function useAutoTranslate(language) {
  const textOriginals = useRef(new WeakMap())
  const attributeOriginals = useRef(new WeakMap())
  const observerRef = useRef(null)

  useLayoutEffect(() => {
    setLanguagePreference(language)
    const root = document.getElementById('root')
    if (!root) return undefined

    const shouldSkip = (node) => {
      const element = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement
      return !element || Boolean(element.closest('[data-no-translate], pre, code, script, style'))
    }

    const translateNode = (node, remember = true) => {
      if (shouldSkip(node)) return
      if (node.nodeType === Node.TEXT_NODE) {
        if (remember || !textOriginals.current.has(node)) textOriginals.current.set(node, node.nodeValue)
        node.nodeValue = translateText(textOriginals.current.get(node), language)
        return
      }
      if (node.nodeType !== Node.ELEMENT_NODE) return
      const originals = attributeOriginals.current.get(node) || new Map()
      for (const attribute of ['placeholder', 'title', 'aria-label']) {
        if (!node.hasAttribute(attribute)) continue
        if (remember || !originals.has(attribute)) originals.set(attribute, node.getAttribute(attribute))
        node.setAttribute(attribute, translateText(originals.get(attribute), language))
      }
      attributeOriginals.current.set(node, originals)
      node.childNodes.forEach((child) => translateNode(child, remember))
    }

    const observer = new MutationObserver((mutations) => {
      observer.disconnect()
      for (const mutation of mutations) {
        if (mutation.type === 'characterData') translateNode(mutation.target, true)
        if (mutation.type === 'attributes') translateNode(mutation.target, true)
        mutation.addedNodes.forEach((node) => translateNode(node, true))
      }
      observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label'] })
    })
    observerRef.current = observer
    observer.disconnect()
    translateNode(root, false)
    observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label'] })
    return () => observer.disconnect()
  }, [language])
}
